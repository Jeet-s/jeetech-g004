/// <reference types="node" />
/**
 * Bakes the UI glyphs (src/ui/glyphs.ts) into white-on-transparent PNGs in assets/icons and writes
 * src/ui/iconAssets.ts (static require()s, so Metro bundles them). Tinted at draw time with Image tintColor.
 *   npx tsx scripts/bake-icons.ts      (needs Google Chrome + the factory's playwright-core; dev tool only)
 */
import { mkdirSync, writeFileSync } from "fs";
import * as path from "path";
import { FILL, HAND, KNUCKLES, STROKE, WEIGHTS } from "../src/ui/glyphs";

const PX = 144;
const out = path.join(__dirname, "../assets/icons");
const wTag = (w: number) => String(w).replace(".", "_");

(async () => {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { chromium } = require(process.env.PLAYWRIGHT_CORE ?? "/Users/jagjeetsingh/ai-game-factory/node_modules/playwright-core");
  const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  const page = await browser.newPage();
  type Job = { file: string; d: string; filled: boolean; weight: number };
  const jobs: Job[] = [];
  for (const [n, d] of Object.entries(STROKE)) for (const w of WEIGHTS) jobs.push({ file: `${n}_${wTag(w)}.png`, d, filled: false, weight: w });
  for (const [n, d] of Object.entries(FILL)) jobs.push({ file: `${n}.png`, d, filled: true, weight: 0 });
  jobs.push({ file: "hand_fill.png", d: HAND, filled: true, weight: 0 });
  jobs.push({ file: "hand_line.png", d: `${HAND} ${KNUCKLES}`, filled: false, weight: 1.5 });
  const pngs: string[] = await page.evaluate(({ jobs, PX }: { jobs: Job[]; PX: number }) => jobs.map((j) => {
    const c = document.createElement("canvas");
    c.width = PX; c.height = PX;
    const g = c.getContext("2d")!;
    g.scale(PX / 24, PX / 24);
    g.fillStyle = g.strokeStyle = "#FFFFFF";
    const p = new Path2D(j.d);
    if (j.filled) g.fill(p);
    else { g.lineWidth = j.weight; g.lineCap = "round"; g.lineJoin = "round"; g.stroke(p); }
    return c.toDataURL("image/png").split(",")[1];
  }), { jobs, PX });
  await browser.close();
  mkdirSync(out, { recursive: true });
  jobs.forEach((j, k) => writeFileSync(path.join(out, j.file), Buffer.from(pngs[k], "base64")));
  const lines = [
    "/* Generated by scripts/bake-icons.ts — do not edit. */",
    "/* eslint-disable @typescript-eslint/no-require-imports */",
    "export const STROKE_ICONS: Record<string, Record<string, number>> = {",
    ...Object.keys(STROKE).map((n) => `  ${JSON.stringify(n)}: { ${WEIGHTS.map((w) => `${JSON.stringify(wTag(w))}: require("../../assets/icons/${n}_${wTag(w)}.png")`).join(", ")} },`),
    "};",
    "export const FILL_ICONS: Record<string, number> = {",
    ...Object.keys(FILL).map((n) => `  ${JSON.stringify(n)}: require("../../assets/icons/${n}.png"),`),
    "};",
    'export const HAND_FILL: number = require("../../assets/icons/hand_fill.png");',
    'export const HAND_LINE: number = require("../../assets/icons/hand_line.png");',
    "",
  ];
  writeFileSync(path.join(__dirname, "../src/ui/iconAssets.ts"), lines.join("\n"));
  console.log(`baked ${jobs.length} glyphs → assets/icons`);
})();
